// Writes the reference pages from the code, so they can't drift from it:
//   content/cli/commands.mdx   from the pyo binary's own help
//   content/mcp/tools.mdx      from the tool list in crates/pyo-api/src/mcp.rs
// Build the CLI first: `cargo build -p pyo-cli` in ../pyo. Then: bun run generate
// For tools.mdx alone, with no pyo binary: bun run scripts/generate.ts --mcp-only
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const PYO_REPO = process.env.PYO_REPO ?? `${root}../pyo`;
const PYO = process.env.PYO_BIN ?? `${PYO_REPO}/target/debug/pyo`;

const MCP_ONLY = process.argv.includes("--mcp-only");

const NOTICE = "{/* Generated by scripts/generate.ts: don't edit by hand. */}";
const help = (...args: string[]) =>
  execFileSync(PYO, [...args, "--help"], { encoding: "utf8" }).trim();

/** Names in a help text's "Commands:" list. */
const subcommands = (text: string) =>
  (/^Commands:\n((?:  \S.*\n?)+)/m.exec(text)?.[1] ?? "")
    .split("\n")
    .map((line) => /^ {2}(\S+)/.exec(line)?.[1])
    .filter((name): name is string => !!name && name !== "help");

// Outside a code block, so placeholders like <team> go in code, or MDX reads them as tags.
const summary = (text: string) => text.split("\n")[0].replace(/<[^<>\s]+>/g, (m) => `\`${m}\``);
const section = (level: string, path: string[]) => {
  const text = help(...path);
  return `${level} \`pyo ${path.join(" ")}\`\n\n${summary(text)}\n\n\`\`\`text\n${text}\n\`\`\`\n`;
};

const commands = MCP_ONLY ? [] : subcommands(help());
if (!MCP_ONLY) {
  const cli = [
    "---",
    "title: Command reference",
    "description: Every command of the pyo CLI.",
    "---",
    "",
    NOTICE,
    "",
    "Add `--help` to any command to see this in your terminal. `--url` and `--token`, or `PYO_URL` and `PYO_TOKEN`, work on every command.",
    "",
    ...commands.flatMap((name) => [
      section("##", [name]),
      ...subcommands(help(name)).map((sub) => section("###", [name, sub])),
    ]),
  ].join("\n");
  writeFileSync(`${root}content/cli/commands.mdx`, cli);
}

// ── MCP tools ────────────────────────────────────────────────────────────────
// The same catalog mcp.rs builds: its written tools first, then one tool per
// API endpoint and /ops operation in openapi/pyo.json, minus the ones a
// written tool covers. The constants below are read from mcp.rs itself.
const source = readFileSync(`${PYO_REPO}/crates/pyo-api/src/mcp.rs`, "utf8");
const spec = JSON.parse(readFileSync(`${root}openapi/pyo.json`, "utf8"));
const schemas = spec.components.schemas;

/** A `const NAME: &[(&str, &str)]` (or `&[&str]`) of mcp.rs. */
const constant = (name: string) => {
  const m = new RegExp(`const ${name}: &\\[[^=]*= &\\[([\\s\\S]*?)\\];`).exec(source);
  if (!m) throw new Error(`No ${name} in mcp.rs`);
  return m[1];
};
const pairs = (name: string) =>
  new Map([...constant(name).matchAll(/\("([^"]+)", "([^"]+)"\)/g)].map((m) => [m[1], m[2]]));
const COVERED = pairs("COVERED");
const RENAMED = pairs("RENAMED");
const CURATED_RUNS = pairs("CURATED_RUNS");
/** Endpoints with no tool. */
const NOT_TOOLS = new Set([...constant("NOT_TOOLS").matchAll(/"([^"]+)"/g)].map((m) => m[1]));
const SECRETS = [...constant("SECRETS").matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const snake = (id: string) => id.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const kebab = (id: string) => snake(id).replace(/_/g, "-");
const tagSlug = (tag: string) => tag.toLowerCase().replace(/\s+/g, "-");
type Access = "Read" | "Deploy" | "Full";
const accessOf = (a: string | undefined): Access =>
  a === "full" || a === "varies" || a === undefined ? "Full" : a === "deploy" ? "Deploy" : "Read";
/** The first paragraph of a spec description, on one line. */
const firstPara = (d = "") =>
  d.split(/\n\s*\n/)[0].replace(/\s*\n\s*/g, " ").trim();

// Everything in the API reference, by operationId or op name.
type Entry = { tag: string; access: Access; title: string; text: string };
const entries = new Map<string, Entry>();
for (const item of Object.values<Record<string, any>>(spec.paths)) {
  for (const e of Object.values<any>(item)) {
    if (!e.operationId || e.operationId === "runOp") continue;
    entries.set(e.operationId, {
      tag: e.tags?.[0] ?? "",
      access: accessOf(e["x-pyo-access"]),
      title: e.summary ?? "",
      text: firstPara(e.description) || e.summary || "",
    });
  }
}
for (const [op, ref] of Object.entries<string>(schemas.Op.discriminator.mapping)) {
  const o = schemas[ref.split("/").pop()!];
  entries.set(op, { tag: o["x-tags"]?.[0] ?? "", access: accessOf(o["x-pyo-access"]), title: o.title ?? op, text: firstPara(o.description) });
}
const reference = (id: string) => {
  const e = entries.get(id);
  if (!e) throw new Error(`${id} isn't in openapi/pyo.json`);
  return `/docs/api/reference/${tagSlug(e.tag)}/${kebab(id)}`;
};

/** The top-level keys of the first `{ ... }` after `from` in mcp.rs. */
function topKeys(text: string, from: number): string[] {
  const open = text.indexOf("{", from);
  const keys: string[] = [];
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      let j = i + 1;
      while (j < text.length && text[j] !== '"') j += text[j] === "\\" ? 2 : 1;
      if (depth === 1 && /^\s*:/.test(text.slice(j + 1, j + 3))) keys.push(text.slice(i + 1, j));
      i = j;
    } else if (c === "{") depth++;
    else if (c === "}" && --depth === 0) break;
  }
  return keys;
}

type Tool = { name: string; text: string; access: Access; link: string; inputs?: string[]; required?: string[]; tag: string };
const curatedAt = source.indexOf("fn curated()");
const starts = [...source.slice(curatedAt).matchAll(/json!\(\{ "name": "([a-z_]+)", "title": "([^"]+)", "description": "((?:[^"\\]|\\.)*)"/g)];
if (!starts.length) throw new Error("Found no written tools in mcp.rs");
const written: Tool[] = starts.map((m, i) => {
  const at = curatedAt + m.index!;
  const end = starts[i + 1] ? curatedAt + starts[i + 1].index! : source.indexOf("\n    ]", at);
  const body = source.slice(at, end);
  const behind = CURATED_RUNS.get(m[1]);
  if (!behind) throw new Error(`${m[1]} has no entry in CURATED_RUNS`);
  const schemaAt = body.indexOf("schema(json!(");
  return {
    name: m[1],
    text: m[3].replace(/\\"/g, '"'),
    access: entries.get(behind)!.access,
    link: reference(behind),
    inputs: topKeys(body, schemaAt),
    required: (/\), &\[([^\]]*)\]\)/.exec(body)?.[1] ?? "").match(/[a-z_]+/g) ?? [],
    tag: "",
  };
});
const generated: Tool[] = [...entries.entries()]
  .filter(([id]) => !COVERED.has(id) && !NOT_TOOLS.has(id))
  .map(([id, e]) => ({
    name: RENAMED.get(id) ?? snake(id),
    text: e.text || e.title,
    access: e.access,
    link: reference(id),
    tag: e.tag,
  }));

// Groups, in reading order; any new tag goes at the end.
const ORDER = ["Account", "State", "Observability", "Services", "Deployments", "Cron jobs", "Databases", "Backups", "Domains", "Volumes", "Teams", "Projects", "Clusters", "Servers", "Firewall", "Builders", "Images", "GitHub", "Integrations"];
const tags = [...new Set(generated.map((t) => t.tag))].sort((a, b) => {
  const i = (t: string) => (ORDER.includes(t) ? ORDER.indexOf(t) : ORDER.length);
  return i(a) - i(b) || a.localeCompare(b);
});

/** A table cell: `|` escaped everywhere; `<` and `{` only outside code spans, which MDX shows as written. */
const cell = (s: string) =>
  s
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, "&lt;").replace(/\{/g, "&#123;")))
    .join("")
    .replace(/\|/g, "\\|");
const secret = (t: Tool) => (SECRETS.some((op) => (RENAMED.get(op) ?? snake(op)) === t.name) ? " Returns a secret." : "");
const writtenTable = [
  "| Tool | What it does | Inputs | Access | API |",
  "| --- | --- | --- | --- | --- |",
  ...written.map(
    (t) =>
      `| \`${t.name}\` | ${cell(t.text)} | ${
        t.inputs!.map((p) => `\`${p}\`${t.required!.includes(p) ? " (required)" : ""}`).join(", ") || "None"
      } | ${t.access} | [Reference](${t.link}) |`,
  ),
].join("\n");
const tagTable = (tag: string) =>
  [
    `## ${tag}`,
    "",
    "| Tool | What it does | Access | API |",
    "| --- | --- | --- | --- |",
    ...generated
      .filter((t) => t.tag === tag)
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((t) => `| \`${t.name}\` | ${cell(t.text)}${secret(t)} | ${t.access} | [Reference](${t.link}) |`),
    "",
  ].join("\n");

const all = [...written, ...generated];
const count = (a: Access) => all.filter((t) => a === "Full" || t.access === "Read" || (a === "Deploy" && t.access === "Deploy")).length;

writeFileSync(
  `${root}content/mcp/tools.mdx`,
  [
    "---",
    "title: Tools",
    "description: Everything an AI assistant can do through Pyo's MCP server.",
    "---",
    "",
    NOTICE,
    "",
    `Pyo's MCP server has ${all.length} tools. They act as the person who approved the assistant, with the same permission checks as the dashboard.`,
    "",
    `An assistant only sees the tools its access allows: ${count("Read")} with **Read only**, ${count("Deploy")} with **Deploy** and all ${count("Full")} with **Full**. See [access](/docs/mcp#choose-what-it-can-do).`,
    "",
    "Most tools do the same as an API operation, and take the same fields. Its reference page lists them.",
    "",
    "## Common tools",
    "",
    "Start with these. They cover what most conversations need.",
    "",
    writtenTable,
    "",
    ...tags.map(tagTable),
  ].join("\n"),
);

console.log(`${MCP_ONLY ? "tools.mdx only, " : `${commands.length} commands, `}${all.length} tools (read ${count("Read")}, deploy ${count("Deploy")}, full ${count("Full")})`);
